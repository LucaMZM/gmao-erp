function insert(
  table: string,
  columns: string[],
  values: SqlValue[],
): Operation {
  return {
    sql: `INSERT INTO ${table} (${columns.join(",")}) VALUES (${values.map(() => "?").join(",")}) ON CONFLICT DO NOTHING`,
    params: values,
  };
}

async function execute(db: D1Database, operations: Operation[]) {
  for (const [index, operation] of operations.entries()) {
    try {
      await db
        .prepare(operation.sql)
        .bind(...operation.params)
        .run();
    } catch (error) {
      throw new Error(
        `V2A seed operation ${index + 1} failed: ${operation.sql}`,
        {
          cause: error,
        },
      );
    }
  }
}

